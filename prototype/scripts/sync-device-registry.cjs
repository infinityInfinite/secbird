// Canonical data -> buildless browser script, also embedded directly by the Rust host.
const fs=require('node:fs');
const path=require('node:path');
const registry=JSON.parse(fs.readFileSync(path.join(__dirname,'../ui/device-registry.json'),'utf8'));
const ids=new Set();
for(const d of registry.devices){
 if(!/^[a-z][a-z0-9-]*$/.test(d.id)||ids.has(d.id)||['constructor','prototype','__proto__'].includes(d.id))throw Error('Invalid/duplicate device id: '+d.id);
 ids.add(d.id);
 const type=registry.types[d.type];if(!type)throw Error('Unknown type: '+d.type);
 if(typeof d.name!=='string'||!d.name.trim())throw Error('Missing device name');
 for(const page of d.pages||type.pages){if(typeof page.label!=='string'||!['mouse-customize','keyboard-customize','lighting','performance','power','calibration','audio','ports'].includes(page.view))throw Error('Unknown page view');}
}
fs.writeFileSync(path.join(__dirname,'../ui/device-registry.js'),'/* Generated by scripts/sync-device-registry.cjs. Edit device-registry.json. */\nwindow.DeviceCatalog = '+JSON.stringify(registry,null,2)+';\n');
