  function resolveLanguage(preference, languages) {
    if (preference === 'en' || preference === 'zh-CN') return preference;
    // Use the user's first preferred language, rather than a lower-priority fallback.
    const first = (languages || [])[0] || 'en';
    return /^zh(?:-|$)/i.test(first) ? 'zh-CN' : 'en';
  }

  function create({ preference = 'auto', languages = ['en'] } = {}) {
    const language = resolveLanguage(preference, languages);
    function text(message, ...values) {
      const tagged = Array.isArray(message) && Object.prototype.hasOwnProperty.call(message, 'raw');
      const key = tagged ? message.map((part, i) => part + (i < values.length ? `{${i}}` : '')).join('') : message;
      const translated = language === 'zh-CN' && Object.prototype.hasOwnProperty.call(zh, key) ? zh[key] : key;
      return tagged ? translated.replace(/\{(\d+)\}/g, (placeholder, n) => n < values.length ? String(values[n]) : placeholder) : translated;
    }
    function plural(n, word) {
      return language === 'zh-CN' ? `${n} ${nouns[word] || word}` : n + ' ' + word + (n === 1 ? '' : 's');
    }
    function applyStatic(document) {
      document.documentElement.lang = language;
      const walker = document.createTreeWalker(document.body, 4 /* SHOW_TEXT */);
      const nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      for (const node of nodes) {
        if (node.parentElement && /^(SCRIPT|STYLE|CODE)$/.test(node.parentElement.tagName)) continue;
        node.textContent = text(node.textContent);
      }
      document.querySelectorAll('[title],[aria-label],[placeholder],option').forEach(element => {
        for (const attribute of ['title', 'aria-label', 'placeholder']) {
          if (element.hasAttribute(attribute)) element.setAttribute(attribute, text(element.getAttribute(attribute)));
        }
        if (element.tagName === 'OPTION') element.textContent = text(element.textContent);
      });
    }
    return { language, text, plural, applyStatic };
  }
  return { create, resolveLanguage, messages: zh };
